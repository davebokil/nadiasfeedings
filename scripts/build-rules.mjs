// Builds firestore.deploy.rules (git-ignored) from firestore.rules by filling in the email allowlist
// from ALLOWED_EMAILS in .env. Keeps real addresses out of the public repo.
//   ALLOWED_EMAILS=you@gmail.com,spouse@gmail.com
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const PLACEHOLDER = "'__ALLOWED_EMAILS__'"

function fromDotEnv(key) {
  if (!existsSync('.env')) return undefined
  for (const line of readFileSync('.env', 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/)
    if (m && m[1] === key) return m[2].replace(/^['"]|['"]$/g, '')
  }
}

const raw = process.env.ALLOWED_EMAILS ?? fromDotEnv('ALLOWED_EMAILS') ?? ''
const emails = raw.split(',').map(s => s.trim().toLowerCase()).filter(Boolean)
const bad = emails.filter(e => !/^[^\s@'"\\]+@[^\s@'"\\]+\.[a-z]{2,}$/.test(e))

if (emails.length === 0) {
  console.error('ALLOWED_EMAILS is empty. Add it to .env, e.g. ALLOWED_EMAILS=you@gmail.com,spouse@gmail.com')
  process.exit(1)
}
if (bad.length) {
  console.error(`ALLOWED_EMAILS has ${bad.length} invalid entr${bad.length === 1 ? 'y' : 'ies'}.`)
  process.exit(1)
}

const template = readFileSync('firestore.rules', 'utf8')
if (!template.includes(PLACEHOLDER)) {
  console.error(`firestore.rules is missing the ${PLACEHOLDER} placeholder.`)
  process.exit(1)
}
const out = '// GENERATED by scripts/build-rules.mjs from firestore.rules. Do not edit or commit.\n' +
  template.replace(PLACEHOLDER, emails.map(e => `'${e}'`).join(',\n          '))
writeFileSync('firestore.deploy.rules', out)
console.log(`Wrote firestore.deploy.rules with ${emails.length} allowed account(s).`)
